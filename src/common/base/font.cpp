/* ------------------------------------------------------------------
   CJK extension (font_cjk.cpp, generated by tools/font_gen_cjk.py).

   A 12px SimSun bitmap atlas covering GB2312 level-1 hanzi + kana +
   CJK punctuation, uploaded once as a 512x1024 PSMT8 texture with a
   2-entry CLUT (0 = transparent, 1 = white; tinting happens through
   the vertex colour MODULATE path, exactly like the ASCII atlas).

   Strings are decoded as UTF-8 first; byte sequences that are not
   valid UTF-8 are re-tried as GBK double-byte codes so Chinese ROM
   filenames in either encoding render correctly.
   ------------------------------------------------------------------ */
extern "C"
{
extern const int    _FontCjkCount;
extern const Uint16 _FontCjkCpSorted[];   /* Unicode cp, ascending   */
extern const Uint16 _FontCjkIdxOfCp[];    /* cp-order -> glyph index */
extern const Uint16 _FontCjkGbkSorted[];  /* GBK code, ascending     */
extern const Uint16 _FontCjkIdxOfGbk[];   /* gbk-order -> glyph idx  */
extern const Uint8  _FontCjkBits[][24];   /* 12 rows x 2 bytes each */
}

#define FONT_CJK_COLS    46
#define FONT_CJK_CELL_W  11
#define FONT_CJK_CELL_H  12
#define FONT_CJK_TEX_W   512
#define FONT_CJK_TEX_H   1024
#define FONT_CJK_ADV     12              /* logical advance (fullwidth) */

/* VRAM offsets from the ASCII atlas TBP, in 256-byte TBP units:
   32 KiB ASCII atlas (0x80 TBP) + 512 KiB CJK texture (0x800 TBP). */
#define FONT_CJK_TBP_OFF   (128)
#define FONT_CJK_CLUT_OFF  (128 + 2048)

/* Marker bit for codepoints produced by the GBK fallback path. */
#define FONT_CP_GBK   0x80000000u

static Int32   _FontCjkTBP    = 0;    /* texture TBP (256B units)      */
static Int32   _FontCjkClutTBP = 0;   /* CLUT   TBP (256B units)       */
static Uint8  *_FontCjkTexBuf = NULL; /* 512 KiB expansion scratch     */
static Uint32  _FontCjkClut[256];
static Int32   _FontTexKind   = -1;   /* -1 none, 0 ascii, 1 cjk       */

/* Decode the next character of p.
   Returns the codepoint (ASCII, Unicode, or FONT_CP_GBK|gbkcode) and
   stores its byte length in *pLen.  Invalid UTF-8 lead bytes (which
   include every GB2312/GBK lead byte) fall back to a two-byte GBK
   decode, so mixed ASCII + GBK filename bytes work naturally. */
static Uint32 _FontDecode(const Char *p, Int32 *pLen)
{
    const unsigned char *s = (const unsigned char *)p;
    unsigned char c = s[0];
    *pLen = 1;

    if (c < 0x80)
        return c;

    if (c >= 0xC2 && c <= 0xDF)
    {
        if ((s[1] & 0xC0) == 0x80)
        {
            *pLen = 2;
            return ((Uint32)(c & 0x1F) << 6) | (Uint32)(s[1] & 0x3F);
        }
    }
    else if (c >= 0xE0 && c <= 0xEF)
    {
        if ((s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80)
        {
            Uint32 cp = ((Uint32)(c & 0x0F) << 12) |
                        ((Uint32)(s[1] & 0x3F) << 6) |
                        (Uint32)(s[2] & 0x3F);
            /* reject overlong encodings */
            if (cp >= 0x800)
            {
                *pLen = 3;
                return cp;
            }
        }
    }
    else if (c >= 0xF0 && c <= 0xF4)
    {
        if ((s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80 &&
            (s[3] & 0xC0) == 0x80)
        {
            *pLen = 4;
            return ((Uint32)(c & 0x07) << 18) |
                   ((Uint32)(s[1] & 0x3F) << 12) |
                   ((Uint32)(s[2] & 0x3F) << 6) |
                   (Uint32)(s[3] & 0x3F);
        }
    }

    /* Not valid UTF-8: try GBK / GB2312 double byte. */
    if (c >= 0x81 && c <= 0xFE &&
        s[1] >= 0x40 && s[1] <= 0xFE && s[1] != 0x7F)
    {
        *pLen = 2;
        return FONT_CP_GBK | ((Uint32)c << 8) | (Uint32)s[1];
    }

    /* Lone continuation / undecodable byte: emit as-is. */
    return c;
}

/* Byte length of the next character (UTF-8 aware).  Public helper so
   the browser's truncation/marquee code can step whole characters
   instead of cutting multi-byte sequences in half. */
Int32 FontCharLen(const Char *pStr)
{
    Int32 len;
    if (!pStr || !*pStr)
        return 0;
    _FontDecode(pStr, &len);
    return len;
}

static Int32 _FontCjkLookupCp(Uint32 cp)
{
    Int32 lo = 0, hi = _FontCjkCount - 1;
    while (lo <= hi)
    {
        Int32 mid = (lo + hi) >> 1;
        if (_FontCjkCpSorted[mid] == (Uint16)cp)
            return (Int32)_FontCjkIdxOfCp[mid];
        if (_FontCjkCpSorted[mid] < cp) lo = mid + 1;
        else                            hi = mid - 1;
    }
    return -1;
}

static Int32 _FontCjkLookupGbk(Uint32 gb)
{
    Int32 lo = 0, hi = _FontCjkCount - 1;
    while (lo <= hi)
    {
        Int32 mid = (lo + hi) >> 1;
        if (_FontCjkGbkSorted[mid] == (Uint16)gb)
            return (Int32)_FontCjkIdxOfGbk[mid];
        if (_FontCjkGbkSorted[mid] < gb) lo = mid + 1;
        else                             hi = mid - 1;
    }
    return -1;
}

/* Resolve a decoded codepoint to a CJK glyph index, or -1. */
static Int32 _FontCjkResolve(Uint32 cp)
{
    if (cp & FONT_CP_GBK)
        return _FontCjkLookupGbk(cp & 0xFFFF);
    return _FontCjkLookupCp(cp);
}

