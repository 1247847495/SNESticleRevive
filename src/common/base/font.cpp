/* Bind either the ASCII atlas or the CJK atlas, skipping redundant
   GPPrimSetTex calls while walking a mixed string. */
static void _FontBindAscii(TextureT *pTexture)
{
    if (_FontTexKind != 0)
    {
        GPPrimSetTex(pTexture->uVramAddr, pTexture->uWidth,
                     pTexture->uWidthLog2, pTexture->uHeightLog2,
                     pTexture->eFormat, 0, 0, 0, 0);
        _FontTexKind = 0;
    }
}

static void _FontBindCjk(void)
{
    if (_FontTexKind != 1 && _FontCjkTBP)
    {
        GPPrimSetTex((u32)_FontCjkTBP, FONT_CJK_TEX_W, 9, 10, GS_PSMT8,
                     (u32)_FontCjkClutTBP, 64, GS_PSMCT32, 0);
        _FontTexKind = 1;
    }
}

static Int32 _FontDrawChar(FontCharT *pFontChar, float fX, float fY, float z1, Uint32 uColor, int c) 
{
	Uint32 u0,v0,u1,v1;
    Uint32 x0,y0,x1,y1;
    Int32 width, height;
    float sx, sy, px0, py0, px1, py1;

    width  = pFontChar->u1 - pFontChar->u0;
    height = pFontChar->v1 - pFontChar->v0;

    /* AURORA_FONT_GS_DDA_240P_V1
     *
     * Pixel-perfect 1:1 glyph rasterisation on the real PS2 GS.
     *
     * The GS sprite DDA does not treat the bottom/right edge like a
     * conventional 2D blitter. Pixel centres are at integer coordinates,
     * while texel centres are at n + 0.5. With the naive UV [u0,u1] /
     * XY [x0,x0+w] mapping a tiny 1x glyph can miss its rightmost texel.
     *
     * In native 240p use the documented GS pixel-perfect convention:
     *   source start : first texel centre             (+0.5000)
     *   source end   : just past last texel centre    (-0.3750 from u1/v1)
     *   dest end     : 1/16 past the last pixel centre
     *
     * This is a sampling/rasterisation fix, NOT a font-content hack:
     * every source column is sampled exactly from the original atlas.
     *
     * Higher framebuffer modes retain Aurora's existing exact integer
     * glyph scaling path, which is already clean there.
     */
    sx = GPPrimGetScaleX(); if (sx <= 0.0f) sx = 1.0f;
    sy = GPPrimGetScaleY(); if (sy <= 0.0f) sy = 1.0f;

    px0 = fX * sx + GPPrimGetOffsetX();
    py0 = fY * sy + GPPrimGetOffsetY();

    if (FONT_DRAW_SCALE == 1 && sx == 1.0f && sy == 1.0f)
    {
        /* UV is 10.4 fixed point: +8 = +0.5, -6 = -0.375. */
        u0 = (pFontChar->u0 << 4) + 8;
        v0 = (pFontChar->v0 << 4) + 8;
        u1 = (pFontChar->u1 << 4) - 6;
        v1 = (pFontChar->v1 << 4) - 6;

        /*
         * Last physical pixel centre is (origin + size - 1).
         * Add the smallest GS subpixel step (1/16) so the right/bottom
         * pixel survives the sprite edge rule without creating a new pixel.
         */
        px1 = px0 + (float)width  - 0.9375f;
        py1 = py0 + (float)height - 0.9375f;
    }
    else
    {
        /* Existing higher-mode integer pixel scaling. */
        u0 = (pFontChar->u0 << 4);
        v0 = (pFontChar->v0 << 4);
        u1 = (pFontChar->u1 << 4);
        v1 = (pFontChar->v1 << 4);

        px1 = px0 + (float)(width  * FONT_DRAW_SCALE);
        py1 = py0 + (float)(height * FONT_DRAW_SCALE);
    }

    x0 = ((Uint32)FIXED4(px0)) & 0xFFFF;
    y0 = ((Uint32)FIXED4(py0)) & 0xFFFF;
    x1 = ((Uint32)FIXED4(px1)) & 0xFFFF;
    y1 = ((Uint32)FIXED4(py1)) & 0xFFFF;

	GPPrimTexRectAbs(x0, y0, u0, v0, x1, y1, u1, v1, 10, uColor, 1);


    /* advance in LOGICAL units: physical glyph width + 2px gap */
    return _FontAdvLogical(width * FONT_DRAW_SCALE + 2);

}

Int32 FontGetStrWidth(const Char *pStr)
{
    Int32 iWidth = 0;
	FontT *pFont;
	pFont = _Font_State.pFont;
	if (!pFont) return 0;

    while (*pStr)
    {
        Int32 len;
        Uint32 cp = _FontDecode(pStr, &len);

		if (cp == ' ')
        {
            // space
		    iWidth += _FontAdvLogical(pFont->uCharX * FONT_DRAW_SCALE);
		}
        else if (cp < 0x80)
        {
            FontCharT *pFontChar = &pFont->CharMap[(unsigned char)cp];
			iWidth += _FontAdvLogical((pFontChar->u1 - pFontChar->u0) * FONT_DRAW_SCALE + 2);
		}
        else
        {
            Int32 gi = _FontCjkResolve(cp);
            if (gi >= 0)
                iWidth += _FontAdvLogical(FONT_CJK_ADV * FONT_DRAW_SCALE);
            else
                iWidth += _FontAdvLogical(6 * FONT_DRAW_SCALE);  /* '?' */
        }

        pStr += len;
	}
	return iWidth;
}


/* Draw one 11x12 CJK cell from the PSMT8 atlas.  Mirrors the pixel-
   perfect integer scaling of _FontDrawChar but with Uint16 atlas
   coordinates (the atlas is 512x1024, beyond the Uint8 CharMap). */
static Int32 _FontDrawCjkGlyph(Int32 gi, Float32 fX, Float32 fY,
                               Uint32 uColor)
{
    Uint32 u, v;
    Uint32 u0, v0, u1, v1;
    Uint32 x0, y0, x1, y1;
    Int32  width, height;
    float sx, sy, px0, py0, px1, py1;

    u = (Uint32)(gi % FONT_CJK_COLS) * FONT_CJK_CELL_W;
    v = (Uint32)(gi / FONT_CJK_COLS) * FONT_CJK_CELL_H;
    width  = FONT_CJK_CELL_W;
    height = FONT_CJK_CELL_H;

    sx = GPPrimGetScaleX(); if (sx <= 0.0f) sx = 1.0f;
    sy = GPPrimGetScaleY(); if (sy <= 0.0f) sy = 1.0f;

    px0 = fX * sx + GPPrimGetOffsetX();
    py0 = fY * sy + GPPrimGetOffsetY();

    if (FONT_DRAW_SCALE == 1 && sx == 1.0f && sy == 1.0f)
    {
        /* pixel-perfect 1:1 (native 240p), same convention as ASCII */
        u0 = (u << 4) + 8;
        v0 = (v << 4) + 8;
        u1 = ((u + width) << 4) - 6;
        v1 = ((v + height) << 4) - 6;
        px1 = px0 + (float)width  - 0.9375f;
        py1 = py0 + (float)height - 0.9375f;
    }
    else
    {
        u0 = (u << 4);
        v0 = (v << 4);
        u1 = ((u + width) << 4);
        v1 = ((v + height) << 4);
        px1 = px0 + (float)(width  * FONT_DRAW_SCALE);
        py1 = py0 + (float)(height * FONT_DRAW_SCALE);
    }

    x0 = ((Uint32)FIXED4(px0)) & 0xFFFF;
    y0 = ((Uint32)FIXED4(py0)) & 0xFFFF;
    x1 = ((Uint32)FIXED4(px1)) & 0xFFFF;
    y1 = ((Uint32)FIXED4(py1)) & 0xFFFF;

    GPPrimTexRectAbs(x0, y0, u0, v0, x1, y1, u1, v1, 10, uColor, 1);

    return _FontAdvLogical(FONT_CJK_ADV * FONT_DRAW_SCALE);
}

static void _FontDrawStr(FontT *pFont, Float32 vx, Float32 vy, Float32 vz, const Char *pStr, Uint32 uColor)
{
    TextureT *pTexture = &pFont->Texture;
    if (!pTexture) return;

    _FontTexKind = -1;   /* force rebind of the first glyph's atlas */

    while (*pStr)
    {
        Int32 len;
        Uint32 cp = _FontDecode(pStr, &len);

        if (cp == ' ')
        {
            vx += _FontAdvLogical(pFont->uCharX * FONT_DRAW_SCALE);
        }
        else if (cp < 0x80)
        {
            _FontBindAscii(pTexture);
            {
                FontCharT *pFontChar = &pFont->CharMap[(unsigned char)cp];
                Int32 iWidth = _FontDrawChar(pFontChar, vx, vy, vz, uColor, (int)cp);
                if (pFont->uFixedWidth) iWidth = _FontAdvLogical((Int32)pFont->uFixedWidth * FONT_DRAW_SCALE);
                vx += iWidth;
            }
        }
        else
        {
            Int32 gi = _FontCjkResolve(cp);
            if (gi >= 0)
            {
                _FontBindCjk();
                /* CJK glyphs are 12px tall vs the 7px ASCII ink; lift
                   them by 2px so mixed lines share a visual baseline. */
                vx += _FontDrawCjkGlyph(gi, vx, vy - 2.0f, uColor);
            }
            else
            {
                _FontBindAscii(pTexture);
                {
                    /* not in the CJK atlas: fall back to '?' */
                    FontCharT *pFontChar = &pFont->CharMap['?'];
                    Int32 iWidth = _FontDrawChar(pFontChar, vx, vy, vz, uColor, '?');
                    if (pFont->uFixedWidth) iWidth = _FontAdvLogical((Int32)pFont->uFixedWidth * FONT_DRAW_SCALE);
                    vx += iWidth;
                }
            }
        }

        pStr += len;
	}
}

static void _FontSetCharMap(FontT *pFont, Uint8 uChar, Uint32 u, Uint32 v, Uint32 w, Uint32 h)
{
	pFont->CharMap[uChar].u0 = u;
	pFont->CharMap[uChar].v0 = v;
	pFont->CharMap[uChar].u1 = u + w;
	pFont->CharMap[uChar].v1 = v + h;
}

static void _FontSetCharSize(FontT *pFont, Uint32 w, Uint32 h)
{
	pFont->uCharX = w;
	pFont->uCharY = h;
}

